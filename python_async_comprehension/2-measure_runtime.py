#!/usr/bin/env python3
"""
A module containing a coroutine that measures the runtime
of four parallel async comprehensions.
"""
import asyncio
import time

async_comprehension = __import__('1-async_comprehension').async_comprehension


async def measure_runtime() -> float:
    """
    Coroutine that runs async_comprehension four times in parallel
    using asyncio.gather and returns the total runtime.
    """
    start: float = time.perf_counter()
    await asyncio.gather(*(async_comprehension() for _ in range(4)))
    end: float = time.perf_counter()
    return end - start
